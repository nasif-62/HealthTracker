using HealthTracker.Helpers;
using HealthTracker.Models;
using HealthTracker.Repositories;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using QContainer = QuestPDF.Infrastructure.IContainer;
using QColors = QuestPDF.Helpers.Colors;

namespace HealthTracker.Services;

public class HealthReportService
{
    private const long WarningSizeBytes = 50 * 1024 * 1024; // 50 MB

    private readonly MedicineRepository _medicineRepo;
    private readonly MedicineScheduleRepository _scheduleRepo;
    private readonly MedicineLogRepository _logRepo;
    private readonly MedicineCourseRepository _courseRepo;
    private readonly DoctorVisitRepository _doctorRepo;
    private readonly MedicalReportRepository _reportRepo;
    private readonly ReportPageRepository _reportPageRepo;
    private readonly HealthMetricRepository _metricRepo;
    private readonly MedicineService _medicineService;
    private readonly PdfTextExtractorService _pdfExtractor;

    public HealthReportService(
        MedicineRepository medicineRepo,
        MedicineScheduleRepository scheduleRepo,
        MedicineLogRepository logRepo,
        MedicineCourseRepository courseRepo,
        DoctorVisitRepository doctorRepo,
        MedicalReportRepository reportRepo,
        ReportPageRepository reportPageRepo,
        HealthMetricRepository metricRepo,
        MedicineService medicineService,
        PdfTextExtractorService pdfExtractor)
    {
        _medicineRepo = medicineRepo;
        _scheduleRepo = scheduleRepo;
        _logRepo = logRepo;
        _courseRepo = courseRepo;
        _doctorRepo = doctorRepo;
        _reportRepo = reportRepo;
        _reportPageRepo = reportPageRepo;
        _metricRepo = metricRepo;
        _medicineService = medicineService;
        _pdfExtractor = pdfExtractor;

        QuestPDF.Settings.License = LicenseType.Community;
    }

    /// <summary>Returns (filePath, warningMessage). warningMessage is null if size is OK.</summary>
    public async Task<(string FilePath, string? Warning)> GenerateAsync(bool includeReportFiles)
    {
        var data = await GatherDataAsync(includeReportFiles);
        var filePath = Path.Combine(FileSystem.CacheDirectory,
            $"HealthReport_{DateTime.Now:yyyyMMdd_HHmmss}.pdf");

        var doc = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(40);
                page.DefaultTextStyle(x => x.FontSize(10).FontColor("#0D1B2A"));

                page.Header().Element(c => BuildHeader(c, data));
                page.Content().Element(c => BuildContent(c, data));
                page.Footer().AlignCenter().Text(t =>
                {
                    t.Span("Generated by HealthTracker · ").FontColor("#5A7A9A").FontSize(8);
                    t.CurrentPageNumber().FontColor("#5A7A9A").FontSize(8);
                    t.Span(" / ").FontColor("#5A7A9A").FontSize(8);
                    t.TotalPages().FontColor("#5A7A9A").FontSize(8);
                });
            });
        });

        doc.GeneratePdf(filePath);

        var fileInfo = new FileInfo(filePath);
        string? warning = fileInfo.Length > WarningSizeBytes
            ? $"Report file is large ({fileInfo.Length / 1024 / 1024} MB). Consider sharing via a file manager or cloud storage."
            : null;

        return (filePath, warning);
    }

    private static void BuildHeader(QContainer c, ReportData data)
    {
        c.BorderBottom(1).BorderColor("#C8D8EA").PaddingBottom(8).Row(row =>
        {
            row.RelativeItem().Column(col =>
            {
                col.Item().Text("Personal Health Report")
                    .FontSize(20).FontColor("#1B5FA8").Bold();
                col.Item().Text($"Generated: {data.GeneratedAt:MMMM d, yyyy  h:mm tt}")
                    .FontSize(9).FontColor("#5A7A9A");
            });
        });
    }

    private static void BuildContent(QContainer c, ReportData data)
    {
        c.Column(col =>
        {
            col.Spacing(20);

            // Section 1: Active Medicines
            if (data.ActiveMedicines.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "1. Active Medicines"));
                foreach (var m in data.ActiveMedicines)
                    col.Item().Element(x => MedicineCard(x, m));
            }

            // Section 2: Past Medicines
            if (data.PastMedicines.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "2. Past Medicines"));
                col.Item().Element(x => PastMedicinesTable(x, data.PastMedicines));
            }

            // Section 3: Dose Log (last 3 months)
            if (data.DoseLogs.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "3. Medicine Dose Log (Last 3 Months)"));
                col.Item().Element(x => DoseLogTable(x, data.DoseLogs));
            }

            // Section 4: Doctor Visits
            if (data.DoctorVisits.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "4. Doctor Visits"));
                foreach (var v in data.DoctorVisits)
                    col.Item().Element(x => DoctorVisitCard(x, v));
            }

            // Section 5: Health Metrics
            if (data.MetricGroups.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "5. Health Metrics"));
                foreach (var (type, metrics) in data.MetricGroups)
                    col.Item().Element(x => MetricsTable(x, type, metrics));
            }

            // Section 6: Medical Reports list
            if (data.MedicalReports.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "6. Medical Reports"));
                col.Item().Element(x => ReportsTable(x, data.MedicalReports));
            }

            // Section 7: Embedded report files
            if (data.ReportImages.Count > 0)
            {
                col.Item().Element(x => SectionHeader(x, "7. Report Files"));
                foreach (var (reportTitle, imageBytes) in data.ReportImages)
                {
                    col.Item().Text(reportTitle).Bold().FontSize(11);
                    col.Item().Image(imageBytes).FitWidth();
                    col.Item().PaddingBottom(10);
                }
            }
        });
    }

    private static void SectionHeader(QContainer c, string title)
    {
        c.Background("#1B5FA8").Padding(8).Text(title)
            .FontColor(QColors.White).Bold().FontSize(13);
    }

    private static void MedicineCard(QContainer c, ActiveMedicineData m)
    {
        c.Border(1).BorderColor("#E0EAF4").Padding(10).Column(col =>
        {
            col.Item().Row(row =>
            {
                row.RelativeItem().Text(m.Name).Bold().FontSize(12);
                row.ConstantItem(80).AlignRight().Text(m.StockUnit).FontColor("#5A7A9A");
            });

            col.Item().PaddingTop(4).Table(t =>
            {
                t.ColumnsDefinition(c => { c.RelativeColumn(); c.RelativeColumn(); });
                AddTableRow(t, "Start Date", m.StartDate);
                AddTableRow(t, "End Date", m.EndDate ?? "Ongoing");
                AddTableRow(t, "Schedule", m.ScheduleTimes);
                AddTableRow(t, "Stock", $"{m.Stock} {m.StockUnit}(s) remaining");
                AddTableRow(t, "Course Progress", m.CourseProgress);
                AddTableRow(t, "Adherence Streak", $"{m.Streak} day(s)");
                AddTableRow(t, "Missed This Week", m.MissedThisWeek.ToString());
                AddTableRow(t, "Compliance (30d)", $"{m.Compliance30d:P0}");
                if (!string.IsNullOrEmpty(m.Instructions)) AddTableRow(t, "Instructions", m.Instructions);
                if (!string.IsNullOrEmpty(m.Notes)) AddTableRow(t, "Notes", m.Notes);
            });
        });
    }

    private static void PastMedicinesTable(QContainer c, List<PastMedicineData> medicines)
    {
        c.Table(t =>
        {
            t.ColumnsDefinition(c =>
            {
                c.RelativeColumn(3); c.RelativeColumn(2); c.RelativeColumn(2);
                c.RelativeColumn(1); c.RelativeColumn(2);
            });
            TableHeader(t, "Name", "Start", "End", "Courses", "Total Doses");
            foreach (var m in medicines)
            {
                TableCell(t, m.Name, bold: true);
                TableCell(t, m.StartDate);
                TableCell(t, m.EndDate ?? "—");
                TableCell(t, m.Courses.ToString());
                TableCell(t, m.TotalDoses.ToString());
            }
        });
    }

    private static void DoseLogTable(QContainer c, List<DoseLogEntry> logs)
    {
        c.Table(t =>
        {
            t.ColumnsDefinition(c =>
            {
                c.RelativeColumn(2); c.RelativeColumn(3); c.RelativeColumn(2); c.RelativeColumn(2);
            });
            TableHeader(t, "Date", "Medicine", "Scheduled", "Status");
            foreach (var log in logs)
            {
                TableCell(t, log.Date);
                TableCell(t, log.MedicineName);
                TableCell(t, log.ScheduledTime);
                var color = log.WasTaken ? "#1A8A4A" : "#C0392B";
                t.Cell().BorderBottom(1).BorderColor("#E0EAF4").Padding(4)
                    .Text(log.WasTaken ? "Taken" : "Missed").FontColor(color).Bold();
            }
        });
    }

    private static void DoctorVisitCard(QContainer c, DoctorVisit v)
    {
        c.Border(1).BorderColor("#E0EAF4").Padding(10).Column(col =>
        {
            col.Item().Row(row =>
            {
                row.RelativeItem().Text(v.DoctorName).Bold().FontSize(11);
                row.ConstantItem(100).AlignRight().Text(v.VisitDate).FontColor("#5A7A9A");
            });
            if (!string.IsNullOrEmpty(v.Hospital))
                col.Item().Text(v.Hospital).FontColor("#5A7A9A").FontSize(9);
            if (!string.IsNullOrEmpty(v.Diagnosis))
                col.Item().PaddingTop(4).Text($"Diagnosis: {v.Diagnosis}").FontSize(10);
            if (!string.IsNullOrEmpty(v.Notes))
                col.Item().PaddingTop(2).Text($"Notes: {v.Notes}").FontSize(10).FontColor("#444444");
            if (!string.IsNullOrEmpty(v.FollowUpDate))
                col.Item().PaddingTop(2).Text($"Follow-up: {v.FollowUpDate}").FontSize(10).FontColor("#1B5FA8");
        });
    }

    private static void MetricsTable(QContainer c, string metricType, List<HealthMetric> metrics)
    {
        c.Column(col =>
        {
            col.Item().Background("#EAF2FB").Padding(6)
                .Text(metricType).Bold().FontSize(11).FontColor("#1B5FA8");
            col.Item().Table(t =>
            {
                t.ColumnsDefinition(c => { c.RelativeColumn(3); c.RelativeColumn(2); c.RelativeColumn(4); });
                TableHeader(t, "Date", "Value", "Notes");
                foreach (var m in metrics)
                {
                    var val = m.SecondValue.HasValue ? $"{m.Value}/{m.SecondValue} {m.Unit}" : $"{m.Value} {m.Unit}";
                    TableCell(t, m.RecordedAt.Length >= 10 ? m.RecordedAt[..10] : m.RecordedAt);
                    TableCell(t, val, bold: true);
                    TableCell(t, m.Notes ?? "—");
                }
            });
        });
    }

    private static void ReportsTable(QContainer c, List<MedicalReport> reports)
    {
        c.Table(t =>
        {
            t.ColumnsDefinition(c =>
            {
                c.RelativeColumn(2); c.RelativeColumn(3); c.RelativeColumn(1);
                c.RelativeColumn(2); c.RelativeColumn(2);
            });
            TableHeader(t, "Date", "Title", "Type", "Doctor", "Hospital");
            foreach (var r in reports)
            {
                TableCell(t, r.ReportDate);
                TableCell(t, r.Title, bold: true);
                TableCell(t, r.ReportType);
                TableCell(t, r.DoctorName ?? "—");
                TableCell(t, r.Hospital ?? "—");
            }
        });
    }

    // Table helpers
    private static void TableHeader(TableDescriptor t, params string[] headers)
    {
        t.Header(h =>
        {
            foreach (var header in headers)
                h.Cell().Background("#1B5FA8").Padding(5).Text(header)
                    .FontColor(QColors.White).Bold().FontSize(9);
        });
    }

    private static void TableCell(TableDescriptor t, string text, bool bold = false)
    {
        var cell = t.Cell().BorderBottom(1).BorderColor("#E0EAF4").Padding(4).Text(text).FontSize(9);
        if (bold) cell.Bold();
    }

    private static void AddTableRow(TableDescriptor t, string label, string value)
    {
        t.Cell().Padding(3).Text(label).FontColor("#5A7A9A").FontSize(9);
        t.Cell().Padding(3).Text(value).FontSize(9);
    }

    // ─── Data Gathering ───────────────────────────────────────────────────────

    private async Task<ReportData> GatherDataAsync(bool includeReportFiles)
    {
        var data = new ReportData { GeneratedAt = DateTime.Now };

        // Active medicines
        var activeMeds = await _medicineRepo.GetAllActiveAsync();
        foreach (var med in activeMeds)
        {
            var schedules = await _scheduleRepo.GetByMedicineIdAsync(med.Id);
            var (streak, missedThisWeek) = await _medicineService.GetAdherenceStats(med.Id);
            var course = await _courseRepo.GetActiveCourseAsync(med.Id);
            var logs30d = await _logRepo.GetLogsForMedicineAsync(med.Id,
                DateTimeHelper.ToDateTimeString(DateTime.Today.AddDays(-30)),
                DateTimeHelper.ToDateTimeString(DateTime.Today.AddDays(1).AddSeconds(-1)));
            var taken30d = logs30d.Count(l => l.WasTaken == 1);
            var total30d = logs30d.Count;
            var compliance = total30d > 0 ? (double)taken30d / total30d : 0;

            data.ActiveMedicines.Add(new ActiveMedicineData
            {
                Name = med.Name,
                StockUnit = med.StockUnit,
                StartDate = med.StartDate,
                EndDate = med.EndDate,
                ScheduleTimes = string.Join(", ", schedules.Select(s => s.ScheduleTime)) +
                                $" ({schedules.Count}x daily)",
                Stock = med.StockCount,
                CourseProgress = course != null
                    ? $"{course.TotalTaken}/{(course.TotalScheduled > 0 ? course.TotalScheduled.ToString() : "∞")} doses"
                    : "—",
                Streak = streak,
                MissedThisWeek = missedThisWeek,
                Compliance30d = compliance,
                Instructions = med.Instructions ?? string.Empty,
                Notes = med.Notes ?? string.Empty
            });
        }

        // Past medicines
        var pastMeds = await _medicineRepo.GetAllInactiveAsync();
        foreach (var med in pastMeds)
        {
            var courses = await _courseRepo.GetByMedicineIdAsync(med.Id);
            data.PastMedicines.Add(new PastMedicineData
            {
                Name = med.Name,
                StartDate = med.StartDate,
                EndDate = med.EndDate,
                Courses = courses.Count,
                TotalDoses = courses.Sum(c => c.TotalTaken)
            });
        }

        // Dose logs last 3 months
        var from3m = DateTimeHelper.ToDateTimeString(DateTime.Today.AddMonths(-3));
        var toNow = DateTimeHelper.ToDateTimeString(DateTime.Today.AddDays(1).AddSeconds(-1));
        var allMeds = activeMeds.Concat(pastMeds).ToList();
        foreach (var med in allMeds)
        {
            var schedules = await _scheduleRepo.GetByMedicineIdAsync(med.Id);
            var logs = await _logRepo.GetLogsForMedicineAsync(med.Id, from3m, toNow);
            foreach (var log in logs.OrderByDescending(l => l.ScheduledFor))
            {
                var sched = schedules.FirstOrDefault(s => s.Id == log.ScheduleId);
                data.DoseLogs.Add(new DoseLogEntry
                {
                    Date = log.ScheduledFor.Length >= 10 ? log.ScheduledFor[..10] : log.ScheduledFor,
                    MedicineName = med.Name,
                    ScheduledTime = sched != null
                        ? (TimeSpan.TryParse(sched.ScheduleTime, out var t)
                            ? DateTime.Today.Add(t).ToString("h:mm tt")
                            : sched.ScheduleTime)
                        : "—",
                    WasTaken = log.WasTaken == 1
                });
            }
        }

        // Doctor visits
        data.DoctorVisits = await _doctorRepo.GetAllOrderedAsync();

        // Health metrics grouped by type
        var allMetrics = await _metricRepo.GetRecentAsync(500);
        data.MetricGroups = allMetrics
            .GroupBy(m => m.MetricType)
            .OrderBy(g => g.Key)
            .ToDictionary(g => g.Key, g => g.OrderByDescending(m => m.RecordedAt).ToList());

        // Medical reports
        data.MedicalReports = await _reportRepo.GetAllOrderedAsync();

        // Embedded report files
        if (includeReportFiles)
        {
            foreach (var report in data.MedicalReports)
            {
                var pages = await _reportPageRepo.GetByReportIdAsync(report.Id);
                foreach (var page in pages.OrderBy(p => p.PageNumber))
                {
                    if (!File.Exists(page.FilePath)) continue;

                    var baseLabel = $"{report.Title} — {report.ReportDate}" +
                                    (pages.Count > 1 ? $" (Page {page.PageNumber})" : "");

                    if (page.FileType.Equals("pdf", StringComparison.OrdinalIgnoreCase))
                    {
                        // ReportPage.PageNumber is the file's ordinal within the report, not a page
                        // inside the PDF, so render every page of the PDF file.
                        var pdfPages = RenderAllPdfPages(page.FilePath);
                        for (int i = 0; i < pdfPages.Count; i++)
                        {
                            var label = pdfPages.Count > 1 ? $"{baseLabel} — PDF page {i + 1}/{pdfPages.Count}" : baseLabel;
                            data.ReportImages.Add((label, pdfPages[i]));
                        }
                    }
                    else
                    {
                        var imageBytes = await File.ReadAllBytesAsync(page.FilePath);
                        if (imageBytes.Length > 0)
                            data.ReportImages.Add((baseLabel, imageBytes));
                    }
                }
            }
        }

        return data;
    }

    /// <summary>Renders every page of a PDF file to JPEG bytes. Returns an empty list on failure.</summary>
    private static List<byte[]> RenderAllPdfPages(string pdfPath)
    {
        var result = new List<byte[]>();
#if ANDROID
        try
        {
            using var fd = Android.OS.ParcelFileDescriptor.Open(
                new Java.IO.File(pdfPath),
                Android.OS.ParcelFileMode.ReadOnly);
            if (fd is null) return result;
            using var renderer = new Android.Graphics.Pdf.PdfRenderer(fd);

            for (int pageIndex = 0; pageIndex < renderer.PageCount; pageIndex++)
            {
                using var page = renderer.OpenPage(pageIndex);
                int width = page.Width * 2;
                int height = page.Height * 2;
                using var bitmap = Android.Graphics.Bitmap.CreateBitmap(width, height,
                    Android.Graphics.Bitmap.Config.Argb8888!);
                page.Render(bitmap, null, null, Android.Graphics.Pdf.PdfRenderMode.ForDisplay);

                using var ms = new MemoryStream();
                bitmap.Compress(Android.Graphics.Bitmap.CompressFormat.Jpeg!, 85, ms);
                result.Add(ms.ToArray());
            }
        }
        catch (Exception ex)
        {
            System.Diagnostics.Debug.WriteLine($"PDF page render failed: {ex.Message}");
        }
#endif
        return result;
    }

    // ─── Data models ──────────────────────────────────────────────────────────

    private class ReportData
    {
        public DateTime GeneratedAt { get; set; }
        public List<ActiveMedicineData> ActiveMedicines { get; } = new();
        public List<PastMedicineData> PastMedicines { get; } = new();
        public List<DoseLogEntry> DoseLogs { get; } = new();
        public List<DoctorVisit> DoctorVisits { get; set; } = new();
        public Dictionary<string, List<HealthMetric>> MetricGroups { get; set; } = new();
        public List<MedicalReport> MedicalReports { get; set; } = new();
        public List<(string Label, byte[] ImageBytes)> ReportImages { get; } = new();
    }

    private class ActiveMedicineData
    {
        public string Name { get; set; } = string.Empty;
        public string StockUnit { get; set; } = string.Empty;
        public string StartDate { get; set; } = string.Empty;
        public string? EndDate { get; set; }
        public string ScheduleTimes { get; set; } = string.Empty;
        public double Stock { get; set; }
        public string CourseProgress { get; set; } = string.Empty;
        public int Streak { get; set; }
        public int MissedThisWeek { get; set; }
        public double Compliance30d { get; set; }
        public string Instructions { get; set; } = string.Empty;
        public string Notes { get; set; } = string.Empty;
    }

    private class PastMedicineData
    {
        public string Name { get; set; } = string.Empty;
        public string StartDate { get; set; } = string.Empty;
        public string? EndDate { get; set; }
        public int Courses { get; set; }
        public int TotalDoses { get; set; }
    }

    private class DoseLogEntry
    {
        public string Date { get; set; } = string.Empty;
        public string MedicineName { get; set; } = string.Empty;
        public string ScheduledTime { get; set; } = string.Empty;
        public bool WasTaken { get; set; }
    }
}
